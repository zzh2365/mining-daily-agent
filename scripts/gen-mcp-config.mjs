#!/usr/bin/env node
// Regenerates mcp-config.json with absolute paths + this machine's node binary,
// for clients that do not resolve relative `args` (Claude Desktop, Cursor).
//   node scripts/gen-mcp-config.mjs                 -> rewrite ./mcp-config.json
//   node scripts/gen-mcp-config.mjs --out /tmp/x.json
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const outFlag = argv.indexOf("--out");
const out = outFlag >= 0 ? resolve(argv[outFlag + 1]) : join(ROOT, "mcp-config.json");

const src = JSON.parse(await readFile(join(ROOT, "mcp-config.json"), "utf8"));

// Client configs (Claude Desktop / Cursor) do not expand ${VAR:-default}, so bake
// the current environment values in as literals. Path-like env vars must be
// absolute: the client launches servers with an arbitrary working directory.
const PATH_KEYS = new Set(["MCP_FIXTURE_DIR", "MCP_CACHE_DIR"]);
const literal = (v) =>
  String(v).replace(/\$\{(\w+)(?::-([^}]*))?\}/g, (_, k, d) => process.env[k] || d || "");

const absolute = {
  ...src,
  $comment:
    "Absolute-path variant generated by scripts/gen-mcp-config.mjs — copy the mcpServers block into Claude Desktop / Cursor config.",
  mcpServers: Object.fromEntries(
    Object.entries(src.mcpServers).map(([name, s]) => [
      name,
      {
        ...s,
        command: process.execPath,
        args: (s.args ?? []).map((a) => resolve(ROOT, literal(a))),
        env: Object.fromEntries(
          Object.entries(s.env ?? {}).map(([k, v]) => {
            const value = literal(v);
            return [k, value && PATH_KEYS.has(k) ? resolve(ROOT, value) : value];
          })
        ),
      },
    ])
  ),
};
await writeFile(out, JSON.stringify(absolute, null, 2) + "\n", "utf8");
console.log(`wrote ${out} (command=${process.execPath})`);
