#!/usr/bin/env node
// mineral-pdf-mcp — NI 43-101 technical report parser
// Tool: extract_resources(pdf_url)
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join, resolve } from "node:path";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";
import { cachedGet, CACHE_DIR, sha1 } from "../../../shared/http.mjs";
import { log } from "../../../shared/log.mjs";
import { extractPdfLines } from "./pdf.mjs";
import { parseNi43101 } from "./ni43101.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..");
const PDF_TTL_MS = 24 * 3600 * 1000;

function textResult(payload) {
  return { content: [{ type: "text", text: JSON.stringify(payload, null, 2) }] };
}

// Accepts http(s) URLs, file:// URLs and bare local paths (incl. relative ones).
function normalizeSource(ref) {
  if (/^https?:\/\//i.test(ref)) return { kind: "http", url: ref };
  if (/^file:\/\//i.test(ref)) return { kind: "file", path: fileURLToPath(ref) };
  const p = resolve(process.env.MCP_FIXTURE_DIR ?? join(ROOT, "fixtures", "pdfs"), ref);
  return { kind: "file", path: p };
}

async function loadPdfBytes(ref) {
  const src = normalizeSource(ref);
  if (src.kind === "file") {
    return { bytes: await readFile(src.path), origin: pathToFileURL(src.path).href, cached: false };
  }
  const cacheKey = join(CACHE_DIR, sha1(src.url) + ".pdf");
  try {
    const st = await (await import("node:fs/promises")).stat(cacheKey);
    if (Date.now() - st.mtimeMs < PDF_TTL_MS) {
      return { bytes: await readFile(cacheKey), origin: src.url, cached: true };
    }
  } catch {}
  const { body } = await cachedGet(src.url, PDF_TTL_MS, { as: "buffer", timeoutMs: 45000 });
  await mkdir(CACHE_DIR, { recursive: true });
  await writeFile(cacheKey, body).catch(() => {});
  return { bytes: body, origin: src.url, cached: false };
}

export const server = new McpServer(
  { name: "mineral-pdf-mcp", version: "1.0.0" },
  {
    instructions:
      "Parses NI 43-101 technical report PDFs and returns structured Mineral Resource estimates " +
      "(Measured / Indicated / Inferred tonnage, grade, contained metal) plus risk flags. " +
      "Call extract_resources(pdf_url) with a report URL or a local fixture path.",
  }
);

server.registerTool(
  "extract_resources",
  {
    title: "Extract NI 43-101 mineral resources from a PDF",
    description:
      "Download a technical report PDF, extract its text layer and parse the NI 43-101 Mineral Resource " +
      "statement. Returns per-category tonnage / grade / contained metal, Measured+Indicated and Inferred " +
      "totals, effective date, qualified person and confidence/risk notes. Also accepts a local path or " +
      "'fixture:<name>' for offline runs.",
    inputSchema: {
      pdf_url: z
        .string()
        .describe("PDF location: https:// URL, file:// URL, local path, or 'fixture:pilbara_ni43101_sample'"),
      max_pages: z.number().int().min(1).max(50).default(20).describe("Pages to scan for the resource table"),
      include_text: z.boolean().default(false).describe("Also return the raw extracted text (verbose)"),
    },
  },
  async ({ pdf_url, max_pages, include_text }) => {
    let ref = pdf_url.trim();
    if (ref.startsWith("fixture:")) {
      ref = join(ROOT, "fixtures", "pdfs", `${ref.slice("fixture:".length)}.pdf`);
    }
    try {
      const { bytes, origin, cached } = await loadPdfBytes(ref);
      const { lines, text, pageCount } = await extractPdfLines(bytes, { maxPages: max_pages });
      const parsed = parseNi43101(lines, text);
      return textResult({
        source: { requested: pdf_url, resolved: origin, used_cache: cached },
        pdf: { pages_scanned: pageCount, extracted_chars: text.length },
        ...parsed,
        ...(include_text ? { text: text.slice(0, 20000) } : {}),
      });
    } catch (err) {
      return textResult({
        source: { requested: pdf_url },
        error: `PDF extraction failed: ${err.message}`,
        hint:
          "Check the URL is reachable, or use 'fixture:pilbara_ni43101_sample' (generated by `npm run fixture-pdf`).",
      });
    }
  }
);

const transport = new StdioServerTransport();
await server.connect(transport);
log("mineral-pdf-mcp ready");
